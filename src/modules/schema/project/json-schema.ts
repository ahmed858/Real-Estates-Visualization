// project.json as a JSON Schema document, for agents and editors outside this codebase.
// Generated from the Zod schema so the two never drift; cross-field rules are listed in its description.
import { z } from "zod";
import { projectConfigShapeSchema } from "./project-schema";

/** Rules checked by parseProjectConfig that a JSON Schema cannot express. */
export const CROSS_FIELD_RULES = [
  "Scene ids are unique across the whole project.",
  "Hotspot ids are unique within their scene.",
  "A { scene } target names an existing scene other than the hotspot's own.",
  "Every hotspot point lies inside its scene image (0 <= x <= width, 0 <= y <= height).",
  "floors (typical floors) is only allowed on kind \"floor\", needs from <= to, and its hotspots use unitSuffix, never unit.",
  "unitSuffix targets are only allowed on a typical floor.",
  "rotation is required on and only allowed on type \"rotation-360\"; model likewise on type \"model-3d\"; panorama likewise on type \"panorama-360\".",
  "Paths are relative to the project folder and never contain \"..\".",
] as const;

/** JSON Schema (draft 2020-12) of the input project.json accepts. */
export function projectConfigJsonSchema(): Record<string, unknown> {
  const raw = z.toJSONSchema(projectConfigShapeSchema, { io: "input", unrepresentable: "any" });
  // The recursive scene gets an anonymous definition name; give it a readable one.
  const generated = JSON.parse(JSON.stringify(raw).replaceAll("__schema0", "Scene")) as Record<string, unknown>;
  return {
    $schema: generated.$schema,
    $id: "https://github.com/ahmed858/Real-Estates-Visualization/project.schema.json",
    title: "Unit Explorer project.json",
    description: [
      "Generated by `npm run generate:schema` from src/modules/schema. Do not edit by hand.",
      "Also checked by `npm run validate` (not expressible here):",
      ...CROSS_FIELD_RULES.map((r) => `- ${r}`),
    ].join("\n"),
    ...Object.fromEntries(Object.entries(generated).filter(([k]) => k !== "$schema")),
  };
}
